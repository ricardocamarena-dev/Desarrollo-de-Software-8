-- Script de inicialización del sistema IoT de seguridad.
-- Ejecutar en Supabase: SQL Editor.

-- Tabla de mediciones de sensores.
create table if not exists public.sensor_readings (
    id bigint generated by default as identity primary key,
    sensor_name text not null,
    value double precision not null,
    unit text,
    created_at timestamptz not null default now()
);

-- Tabla de eventos de seguridad detectados por el sistema.
create table if not exists public.security_events (
    id bigint generated by default as identity primary key,
    event_type text not null,
    description text,
    severity_level text,
    created_at timestamptz not null default now()
);

-- Tabla de comandos enviados al sistema y su estado de ejecución.
create table if not exists public.executed_commands (
    id bigint generated by default as identity primary key,
    command_name text,
    origin text,
    status text,
    created_at timestamptz not null default now()
);

-- Permitir que el rol anon acceda al esquema public.
grant usage on schema public to anon;

-- Permitir inserciones REST desde bridge.py.
grant insert on table public.sensor_readings to anon;
grant insert on table public.security_events to anon;
grant insert on table public.executed_commands to anon;

-- Permitir la lectura del contenido devuelto por las operaciones INSERT.
-- El cliente supabase-py puede solicitar la fila insertada en la respuesta.
grant select on table public.sensor_readings to anon;
grant select on table public.security_events to anon;
grant select on table public.executed_commands to anon;

-- Habilitar Row Level Security en las tres tablas.
alter table public.sensor_readings enable row level security;
alter table public.security_events enable row level security;
alter table public.executed_commands enable row level security;

-- Eliminar políticas antiguas con nombres conocidos antes de recrearlas.
drop policy if exists "anon_insert_sensor_readings" on public.sensor_readings;
drop policy if exists "anon_select_sensor_readings" on public.sensor_readings;
drop policy if exists "anon_insert_security_events" on public.security_events;
drop policy if exists "anon_select_security_events" on public.security_events;
drop policy if exists "anon_insert_executed_commands" on public.executed_commands;
drop policy if exists "anon_select_executed_commands" on public.executed_commands;

-- Permitir únicamente inserciones anónimas en lecturas de sensores.
create policy "anon_insert_sensor_readings"
on public.sensor_readings
for insert
to anon
with check (true);

-- Permitir consultas anónimas opcionales de lecturas de sensores.
create policy "anon_select_sensor_readings"
on public.sensor_readings
for select
to anon
using (true);

-- Permitir únicamente inserciones anónimas en eventos de seguridad.
create policy "anon_insert_security_events"
on public.security_events
for insert
to anon
with check (true);

-- Permitir consultas anónimas opcionales de eventos de seguridad.
create policy "anon_select_security_events"
on public.security_events
for select
to anon
using (true);

-- Permitir únicamente inserciones anónimas en comandos ejecutados.
create policy "anon_insert_executed_commands"
on public.executed_commands
for insert
to anon
with check (true);

-- Permitir consultas anónimas opcionales de comandos ejecutados.
create policy "anon_select_executed_commands"
on public.executed_commands
for select
to anon
using (true);

-- Verificación de permisos de tablas concedidos al rol anon.
select grantee, table_name, privilege_type
from information_schema.role_table_grants
where table_schema = 'public'
  and grantee = 'anon'
  and table_name in (
      'sensor_readings',
      'security_events',
      'executed_commands'
  )
order by table_name, privilege_type;

-- Verificación de las políticas RLS activas.
select schemaname, tablename, policyname, roles, cmd
from pg_policies
where schemaname = 'public'
  and tablename in (
      'sensor_readings',
      'security_events',
      'executed_commands'
  )
order by tablename, policyname;
